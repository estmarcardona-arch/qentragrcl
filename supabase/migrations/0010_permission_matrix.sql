-- 0010_permission_matrix.sql · Etapa E2 (administración)
-- Matriz de permisos por módulo y rol (PRD 2.2): L = leer, C = crear/editar borrador, F = firmar,
-- A = aprobar. Los datos se generaron desde docs/PRD_GRUFARCOL.md con scripts/gen-permission-matrix.ts;
-- la prueba E2E compara la pantalla S-04 con el PRD. Es de solo lectura (se cambia por migración).
-- Las políticas RLS de las etapas siguientes consultan has_module_permission().

create table public.permission_modules (
  code text primary key,
  name text not null,
  order_no int not null unique,
  created_at timestamptz not null default now(),
  created_by uuid,
  updated_at timestamptz not null default now(),
  updated_by uuid
);

create table public.module_permissions (
  id uuid primary key default gen_random_uuid(),
  module_code text not null references public.permission_modules (code),
  role public.app_role not null,
  cell_text text not null,
  can_read boolean not null,
  can_create boolean not null,
  can_sign boolean not null,
  can_approve boolean not null,
  created_at timestamptz not null default now(),
  created_by uuid,
  updated_at timestamptz not null default now(),
  updated_by uuid,
  unique (module_code, role)
);

comment on table public.module_permissions is
  'Matriz de permisos del PRD 2.2 (texto de la celda y banderas L/C/F/A). Solo lectura.';

alter table public.permission_modules enable row level security;
alter table public.module_permissions enable row level security;
select app_private.register_table('public.permission_modules', p_append_only => true);
select app_private.register_table('public.module_permissions', p_append_only => true);
create policy "authenticated can read permission modules" on public.permission_modules
  for select to authenticated using (true);
create policy "authenticated can read module permissions" on public.module_permissions
  for select to authenticated using (true);
revoke all on table public.permission_modules, public.module_permissions from anon;
revoke insert, update, delete, truncate on table public.permission_modules, public.module_permissions
  from authenticated;

