-- ¿El usuario actual tiene el permiso en el módulo? (read, create, sign, approve)
create or replace function public.has_module_permission(p_module text, p_permission text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.module_permissions mp
    where mp.module_code = p_module
      and mp.role = any(public.current_user_roles())
      and case p_permission
            when 'read' then mp.can_read or mp.can_create or mp.can_sign or mp.can_approve
            when 'create' then mp.can_create
            when 'sign' then mp.can_sign
            when 'approve' then mp.can_approve
            else false
          end
  );
$$;

revoke execute on function public.has_module_permission(text, text) from public, anon;
grant execute on function public.has_module_permission(text, text) to authenticated;
